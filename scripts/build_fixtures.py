#!/usr/bin/env python
"""Build and verify the synthetic CyberSwarm fixtures (stage S1).

The storyboard module :mod:`fixture_storyboard` holds the literal data; this
script turns it into committed files and checks them. It is deterministic: the
same storyboard always produces byte-identical files, so ``--check`` can detect
any drift between the committed fixtures and a fresh regeneration.

Usage (run from the repository root with the repo-local interpreter)::

    .venv/bin/python scripts/build_fixtures.py --write
    .venv/bin/python scripts/build_fixtures.py --check

``--write`` writes every fixture under ``fixtures/`` (the S1 valid/invalid
records and primary mini-episode from :mod:`fixture_storyboard`, plus the S3
graph records derived through the real converter in :mod:`graph_fixtures`) after
verifying that each valid record constructs through its model, each invalid
record fails for its one intended reason, and the mini-episode is cross-record
consistent. ``--check`` regenerates everything in memory and compares it
byte-for-byte against the committed files, exiting non-zero on any drift. Every
path written is repository-relative.

The S1 records come from the literal, contracts-only storyboard; the S3 graph
snapshots and features are derived by running :mod:`cyberswarm.graph` on the
storyboard's observation inputs (DESIGN section 8), so this script - not the
storyboard - is the one that imports the graph package.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# The storyboard lives next to this script; make it importable when the script
# is run directly from any working directory.
_SCRIPT_DIR = Path(__file__).resolve().parent
if str(_SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPT_DIR))

from cyberswarm.contracts import (  # noqa: E402  (after sys.path setup)
    RECORD_TYPES,
    EpisodeRecordSet,
    check_episode,
    dumps_canonical,
)

import fixture_storyboard as sb  # noqa: E402
import graph_fixtures as gf  # noqa: E402

REPO_ROOT = _SCRIPT_DIR.parent
#: Directories whose entire contents are generated by this script.
MANAGED_DIRS = (
    "fixtures/records/valid",
    "fixtures/records/invalid",
    "fixtures/mini_episode",
)


# --------------------------------------------------------------------------- #
# Fixture sources (S1 storyboard + S3 derived graph records)
# --------------------------------------------------------------------------- #
def _all_valid_fixtures() -> list[sb.ValidFixture]:
    """Every valid single-record fixture: S1 storyboard then S3 graph records."""

    return [*sb.valid_fixtures(), *gf.valid_graph_fixtures()]


def _all_invalid_fixtures() -> list[sb.InvalidFixture]:
    """Every invalid single-record fixture: S1 storyboard then S3 graph records."""

    return [*sb.invalid_fixtures(), *gf.invalid_graph_fixtures()]


# --------------------------------------------------------------------------- #
# Serialization
# --------------------------------------------------------------------------- #
def _canonical_payload_json(payload: object) -> str:
    """Canonical JSON for a raw (invalid) payload, matching ``dumps_canonical``."""

    return json.dumps(payload, ensure_ascii=True, separators=(",", ":"), allow_nan=True)


def build_all_files() -> dict[str, str]:
    """Return ``{repo_relative_path: file_text}`` for every generated fixture."""

    files: dict[str, str] = {}

    for fixture in _all_valid_fixtures():
        files[fixture.rel_path] = dumps_canonical(fixture.model) + "\n"

    for fixture in _all_invalid_fixtures():
        files[fixture.rel_path] = _canonical_payload_json(fixture.payload) + "\n"

    for episode_file in sb.mini_episode_files():
        if episode_file.is_jsonl:
            files[episode_file.rel_path] = "".join(
                dumps_canonical(record) + "\n" for record in episode_file.records
            )
        else:
            files[episode_file.rel_path] = (
                dumps_canonical(episode_file.records[0]) + "\n"
            )

    return files


# --------------------------------------------------------------------------- #
# Verification (independent of the on-disk files)
# --------------------------------------------------------------------------- #
def verify_valid() -> list[str]:
    """Confirm every valid fixture validates through its pydantic model."""

    report: list[str] = []
    for fixture in _all_valid_fixtures():
        record_type = type(fixture.model).__name__
        model_cls = RECORD_TYPES[record_type]
        # Re-validate from the serialized form to prove a round trip, not just
        # that the in-memory object exists.
        model_cls.model_validate(json.loads(dumps_canonical(fixture.model)))
        report.append(f"  OK  {fixture.rel_path}  ({record_type})")
    return report


def verify_invalid() -> list[str]:
    """Confirm every invalid fixture fails validation for its one reason."""

    report: list[str] = []
    for fixture in _all_invalid_fixtures():
        model_cls = RECORD_TYPES[fixture.record_type]
        try:
            model_cls.model_validate(fixture.payload)
        except Exception as exc:  # noqa: BLE001 - we want any validation failure
            detail = str(exc).splitlines()[0][:80]
            report.append(
                f"  OK  {fixture.rel_path}  -> {fixture.reason} "
                f"[{type(exc).__name__}: {detail}]"
            )
        else:
            raise SystemExit(
                f"ERROR: invalid fixture unexpectedly validated: {fixture.rel_path}"
            )
    return report


def verify_mini_episode() -> list[str]:
    """Confirm the mini-episode has no cross-record consistency issues."""

    episode = sb.mini_episode()
    record_set = EpisodeRecordSet(
        events=list(episode.events),
        observations=list(episode.observations),
        available_actions=list(episode.available_actions),
        detection=list(episode.detection),
        node_scores=list(episode.node_scores),
        proposals=list(episode.proposals),
        validations=list(episode.validations),
        executions=list(episode.executions),
        ground_truth=list(episode.ground_truth),
        episode_result=episode.episode_result,
    )
    issues = check_episode(record_set, episode.topology)
    if issues:
        lines = "\n".join(f"    {issue.rule}: {issue.message}" for issue in issues)
        raise SystemExit(
            f"ERROR: mini-episode has {len(issues)} consistency issue(s):\n{lines}"
        )
    return [f"  OK  mini-episode consistent ({len(episode.events)} events, "
            f"{len(episode.proposals)} proposals, 0 issues)"]


def verify_all() -> tuple[list[str], list[str], list[str]]:
    """Run every verification and return the three report sections."""

    return verify_valid(), verify_invalid(), verify_mini_episode()


# --------------------------------------------------------------------------- #
# Commands
# --------------------------------------------------------------------------- #
def _iter_committed_files() -> list[str]:
    """Repository-relative paths of every file in the managed directories."""

    found: list[str] = []
    for managed in MANAGED_DIRS:
        base = REPO_ROOT / managed
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.is_file():
                found.append(path.relative_to(REPO_ROOT).as_posix())
    return found


def command_write() -> int:
    """Verify, then write every fixture, and report what was written."""

    valid_report, invalid_report, mini_report = verify_all()
    files = build_all_files()

    for rel_path, text in sorted(files.items()):
        target = REPO_ROOT / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")

    print(f"Wrote {len(files)} fixture files under fixtures/:")
    for rel_path in sorted(files):
        print(f"  {rel_path}")

    print(f"\nValid fixtures ({len(valid_report)}) construct through their models:")
    print("\n".join(valid_report))

    print(f"\nInvalid fixtures ({len(invalid_report)}) fail for one reason each:")
    print("\n".join(invalid_report))

    print("\nMini-episode:")
    print("\n".join(mini_report))
    return 0


def command_check() -> int:
    """Regenerate in memory and compare byte-for-byte with the committed files."""

    # Verification also runs here so --check catches a storyboard that no longer
    # validates, not only textual drift.
    verify_all()

    files = build_all_files()
    expected = set(files)
    committed = set(_iter_committed_files())

    drift: list[str] = []

    for rel_path in sorted(expected):
        target = REPO_ROOT / rel_path
        if not target.exists():
            drift.append(f"  MISSING   {rel_path}")
            continue
        on_disk = target.read_text(encoding="utf-8")
        if on_disk != files[rel_path]:
            drift.append(f"  DIFFERENT {rel_path}")

    for rel_path in sorted(committed - expected):
        drift.append(f"  STALE     {rel_path}")

    if drift:
        print(f"Fixture drift detected ({len(drift)} file(s)):")
        print("\n".join(drift))
        print("\nRun: .venv/bin/python scripts/build_fixtures.py --write")
        return 1

    print(f"Fixtures up to date: zero drift across {len(expected)} files.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--write", action="store_true", help="write every fixture under fixtures/"
    )
    group.add_argument(
        "--check",
        action="store_true",
        help="compare committed fixtures with a fresh regeneration",
    )
    args = parser.parse_args(argv)

    if args.write:
        return command_write()
    return command_check()


if __name__ == "__main__":
    raise SystemExit(main())
